#!/usr/bin/env python3
"""Generates FernReader's adaptive launcher icon (original artwork, MIT like the repo).

A single fern frond: a gently curved stem with alternating leaflets that shorten toward the tip, on a calm
deep-green background. Writes the foreground/monochrome vector drawables (108 x 108 dp viewport, artwork kept
inside the 66 dp safe zone) and an SVG preview. Run: python3 -I tools/icon/gen_fern.py
"""
import math, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res"

P0, P1, P2 = (51.0, 84.0), (47.0, 55.0), (66.0, 25.0)   # stem: quadratic Bezier, base to tip
BG, LEAF, STEM = "#FF234A3F", "#FFCFE8C4", "#FFB3D9A6"


def bez(t):
    u = 1 - t
    return tuple(u * u * a + 2 * u * t * b + t * t * c for a, b, c in zip(P0, P1, P2))


def tangent(t):
    d = tuple(2 * (1 - t) * (b - a) + 2 * t * (c - b) for a, b, c in zip(P0, P1, P2))
    n = math.hypot(*d)
    return d[0] / n, d[1] / n


def rot(v, deg):
    r = math.radians(deg)
    return v[0] * math.cos(r) - v[1] * math.sin(r), v[0] * math.sin(r) + v[1] * math.cos(r)


def leaf(base, direction, length, width):
    tip = (base[0] + direction[0] * length, base[1] + direction[1] * length)
    nx, ny = -direction[1], direction[0]
    mid = (base[0] + direction[0] * length * 0.45, base[1] + direction[1] * length * 0.45)
    c1 = (mid[0] + nx * width, mid[1] + ny * width)
    c2 = (mid[0] - nx * width, mid[1] - ny * width)
    f = lambda p: f"{p[0]:.2f},{p[1]:.2f}"
    return f"M{f(base)} Q{f(c1)} {f(tip)} Q{f(c2)} {f(base)} Z"


def frond():
    paths = []
    n = 9
    for i in range(n):
        t = 0.10 + 0.80 * i / (n - 1)
        base = bez(t)
        tan = tangent(t)
        length = 19.0 * (1 - t) + 4.5
        width = length * 0.19
        for side in (-1, 1):
            # leaflets sweep forward (toward the tip), alternating a little along the stem
            tt = min(t + (0.045 if side > 0 else 0.0), 0.95)
            b = bez(tt)
            d = rot(tangent(tt), side * (62 if side < 0 else 52))
            paths.append(leaf(b, d, length, width))
    tip = bez(1.0)
    td = tangent(1.0)
    paths.append(leaf(bez(0.96), td, 5.5, 1.6))
    return paths


def stem_path():
    f = lambda p: f"{p[0]:.2f},{p[1]:.2f}"
    return f"M{f(P0)} Q{f(P1)} {f(P2)}"


def vector(fill_leaf, fill_stem):
    leaves = "\n".join(f'    <path android:fillColor="{fill_leaf}" android:pathData="{p}" />' for p in frond())
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon/gen_fern.py (original FernReader artwork). Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:strokeColor="{fill_stem}" android:strokeWidth="2.4" android:strokeLineCap="round"
        android:pathData="{stem_path()}" />
{leaves}
</vector>
'''


def main():
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
    (RES / "values").mkdir(parents=True, exist_ok=True)
    (RES / "drawable/ic_launcher_foreground.xml").write_text(vector(LEAF, STEM))
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector("#FF000000", "#FF000000"))
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{BG}</color>\n</resources>\n')
    adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''
    (RES / "mipmap-anydpi-v26/ic_launcher.xml").write_text(adaptive)
    (RES / "mipmap-anydpi-v26/ic_launcher_round.xml").write_text(adaptive)
    hexc = lambda c: "#" + c[3:]
    leaves = "".join(f'<path fill="{hexc(LEAF)}" d="{p}"/>' for p in frond())
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432">'
           f'<defs><clipPath id="c"><circle cx="54" cy="54" r="54"/></clipPath></defs><g clip-path="url(#c)">'
           f'<rect width="108" height="108" fill="{hexc(BG)}"/>'
           f'<path d="{stem_path()}" stroke="{hexc(STEM)}" stroke-width="2.4" stroke-linecap="round" fill="none"/>{leaves}</g></svg>')
    (ROOT / "tools/icon/fern-preview.svg").write_text(svg)


if __name__ == "__main__":
    main()
